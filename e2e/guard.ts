import { spawnSync } from "node:child_process";

/**
 * پیش از هر آزمونی: مطمئن شو هدف، پایگاه دادهٔ محلی است.
 *
 * دلیلش یک آزمون است — «ثبت استعلام» واقعاً یک سفارش می‌نویسد. اگر این مجموعه
 * اشتباهی روی production اجرا شود، سفارش جعلی در صف تیم فروش می‌نشیند و
 * شمارندهٔ شماره هم جلو می‌رود.
 *
 * همان محافظِ اسکریپت‌های داده‌ای به‌کار می‌رود، و به‌صورت پروسهٔ جدا صدا زده
 * می‌شود نه import: آن فایل ماژول ESM است و اجراکنندهٔ آزمون آن را به CJS
 * ترجمه می‌کند، جایی که import.meta معنا ندارد. اجرای مستقیم همان راهی است که
 * package.json هم از آن استفاده می‌کند، پس دو نسخه از یک قاعده نمی‌ماند.
 */
export default function globalSetup() {
  const result = spawnSync(process.execPath, ["scripts/guard-destructive.mjs", "آزمون‌های دود"], {
    stdio: "inherit",
  });
  if (result.status !== 0) {
    throw new Error("آزمون‌ها اجرا نشدند — هدف پایگاه دادهٔ محلی نیست.");
  }
}
