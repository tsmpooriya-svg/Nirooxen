/**
 * =============================================================================
 *  نامک برند
 * =============================================================================
 *  نامک باید از املای لاتین برند ساخته شود، نه از چکیدهٔ نام فارسی. پنل مدیریت
 *  هم همین کار را می‌کند (src/modules/admin/actions.ts: slug ← latinName)، پس
 *  واردکننده‌ها هم باید همان قاعده را دنبال کنند تا برندی که از پنل ساخته شده
 *  با برندی که از کاتالوگ آمده آدرس هم‌شکل داشته باشد.
 *
 *  سابقه: نسخهٔ نخست نامک را از چند بایت نخستِ نام فارسی می‌ساخت؛ «اسپیل» و
 *  «اسپینا» روی هم افتادند و یک برند بی‌صدا از ۱۱ محصول حذف شد. رفعِ عجولانه‌اش
 *  چکیدهٔ کامل SHA-256 بود که تصادم را برد ولی آدرس‌هایی مثل
 *  /brands/brand-59b40fe8e13238b86a28c330 به‌جا گذاشت. قاعدهٔ درست همین‌جاست:
 *  املای لاتین، و چکیده فقط به‌عنوان آخرین چاره.
 * =============================================================================
 */
import { createHash } from "node:crypto";

/**
 * املای لاتین برندهایی که در فایل‌های کاتالوگ ستون brandLatin ندارند.
 * مبنای هر کدام در ستون سوم آمده؛ هیچ‌کدام بدون دلیل نوشته نشده.
 */
export const BRAND_LATIN = {
  "3M": "3M",                       // خودِ نام لاتین است
  "هیوندای": "Hyundai",             // نام فایل عکس در کاتالوگ منبع: hyundai-hb.webp
  "توان تک": "Tavantak",            // نام فایل عکس در کاتالوگ منبع: tavantak-tmr.webp
  "آریا کوپلینگ": "Aria Coupling",  // از نشانی سایت خودِ برند که کارفرما فرستاد
  "آریا": "Aria",
  "الماس": "Almas",
  "اینترلوک": "Interlock",
  "سیف هوم": "Safe Home",
  "لوتوس": "Lotus",
  "هافل": "Hafele",
};

/**
 * همان قاعدهٔ slugify برنامه (src/lib/utils.ts). اینجا تکرار شده چون این
 * اسکریپت‌ها node خام‌اند و ماژول TypeScript را مستقیم نمی‌توانند بخوانند.
 */
export function slugifyLatin(input) {
  return input
    .trim()
    .replace(/[‌‏‎]/g, "-")
    .replace(/[^\p{L}\p{N}]+/gu, "-")
    .replace(/^-+|-+$/g, "")
    .replace(/-{2,}/g, "-")
    .toLowerCase();
}

/** نامکِ چکیده‌ای — فقط وقتی املای لاتین نداریم یا نامک لاتین تصادم دارد */
export function hashSlug(nameFa) {
  return "brand-" + createHash("sha256").update(nameFa, "utf8").digest("hex").slice(0, 24);
}

/**
 * املای لاتین برند را برمی‌گرداند: اول از خود ردیف کاتالوگ، بعد از جدول بالا.
 * اگر هیچ‌کدام نبود null — یعنی حق نداریم آوانویسی را حدس بزنیم.
 */
export function latinFor(nameFa, fromRow) {
  return (fromRow && String(fromRow).trim()) || BRAND_LATIN[nameFa] || null;
}

/**
 * نامک نهایی برند.
 *
 * `taken` نگاشت «نامک ← نام برندی که آن را گرفته» است. اگر نامک لاتین را برند
 * دیگری برداشته باشد، به چکیده برمی‌گردیم — تصادم هرگز نباید به‌صورت بی‌صدا
 * دو برند را یکی کند، که همان اشکال اولیه بود.
 */
export function brandSlug(nameFa, fromRow, taken = {}) {
  const latin = latinFor(nameFa, fromRow);
  if (latin) {
    const slug = slugifyLatin(latin);
    if (slug && (!taken[slug] || taken[slug] === nameFa)) return slug;
  }
  return hashSlug(nameFa);
}
