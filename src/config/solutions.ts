/**
 * =============================================================================
 *  راهکارها (Solutions) — تعریف محتوایی
 * =============================================================================
 *  نقطه ورود کاربر بر اساس «مسئله»، نه بر اساس «نام محصول».
 *
 *      من چه نیازی دارم؟  →  نیروژن چه راهکاری برای من دارد؟
 *
 *  چرا اینجا و نه در پایگاه داده؟
 *  ---------------------------------------------------------------------------
 *  یک راهکار دو بخش دارد:
 *
 *    ۱. محتوای تحریریه‌ای (پرسش کاربر، شرح وضعیت، نکات فنی) — کم‌تغییر است و
 *       مثل `services` و `mainNav` در همین لایه پیکربندی نگهداری می‌شود.
 *    ۲. داده کاتالوگ (دسته‌بندی‌ها و محصولات) — از پایگاه داده خوانده می‌شود.
 *
 *  اتصال این دو با «اسلاگ دسته‌بندی» و «برچسب محصول» انجام می‌شود؛ هر دو
 *  از قبل در اسکیما وجود دارند (`categories.slug` و `products.tags`).
 *  بنابراین افزودن راهکار جدید هیچ migration ای لازم ندارد.
 *
 *  افزودن راهکار تازه:
 *  ---------------------------------------------------------------------------
 *    ۱. یک شیء به آرایه `solutions` اضافه کنید.
 *    ۲. `categorySlugs` را از اسلاگ‌های موجود در جدول `categories` انتخاب کنید.
 *    ۳. `productTags` را از برچسب‌های موجود در `products.tags` انتخاب کنید.
 *
 *  هیچ تغییری در کامپوننت‌ها لازم نیست؛ صفحه‌ها این آرایه را پیمایش می‌کنند.
 *  اگر راهکاری هنوز محصولی نداشته باشد، رابط کاربری حالت خالی مناسب نشان
 *  می‌دهد و چیزی از خود نمی‌سازد.
 * =============================================================================
 */

