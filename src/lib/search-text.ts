/**
 * =============================================================================
 *  یکسان‌سازی متن برای جستجو
 * =============================================================================
 *  دو مسیر جستجو داریم — دیالوگ Ctrl+K و صافی صفحهٔ محصولات — و هر دو باید
 *  دقیقاً یک قاعده داشته باشند، وگرنه یک عبارت در دو جای سایت دو نتیجه می‌دهد.
 *  پس جدول تبدیل یک‌بار اینجا تعریف می‌شود و هر دو طرفِ مقایسه از همین می‌آیند:
 *  سمت SQL با translate روی ستون، و سمت جاوااسکریپت روی ورودی کاربر.
 *
 *  چرا حروف عربی؟ داده‌های ما فارسیِ تمیزند، ولی کاربر ایرانی نیمی از وقت‌ها
 *  با کیبورد عربی تایپ می‌کند یا از جای دیگر کپی می‌کند. بدون این تبدیل،
 *  «كپسول» با کافِ عربی هیچ نتیجه‌ای نمی‌داد، در حالی که ده‌ها کپسول در
 *  کاتالوگ هست. همین برای «ي» عربی در «شيلنگ» و مانند آن.
 * =============================================================================
 */
import { sql, type AnyColumn, type SQL } from "drizzle-orm";

/**
 * نگاشت یک‌به‌یک. ترتیبش مهم نیست ولی تکراری نباید داشته باشد، چون
 * translate در پستگرس اولین تطبیق را می‌گیرد.
 */
const FOLD_PAIRS: ReadonlyArray<readonly [string, string]> = [
  // ارقام فارسی و عربی → لاتین
  ["۰", "0"], ["۱", "1"], ["۲", "2"], ["۳", "3"], ["۴", "4"],
  ["۵", "5"], ["۶", "6"], ["۷", "7"], ["۸", "8"], ["۹", "9"],
  ["٠", "0"], ["١", "1"], ["٢", "2"], ["٣", "3"], ["٤", "4"],
  ["٥", "5"], ["٦", "6"], ["٧", "7"], ["٨", "8"], ["٩", "9"],

  // حروفی که در عربی و فارسی شکل متفاوت دارند و کاربر هر دو را تایپ می‌کند
  ["ي", "ی"], // ي → ی
  ["ى", "ی"], // ى → ی
  ["ئ", "ی"], // ئ → ی
  ["ك", "ک"], // ك → ک
  ["ة", "ه"], // ة → ه
  ["ۀ", "ه"], // ۀ → ه
  ["أ", "ا"], // أ → ا
  ["إ", "ا"], // إ → ا
  ["آ", "ا"], // آ → ا
  ["ٱ", "ا"], // ٱ → ا
  ["ؤ", "و"], // ؤ → و
];

/**
 * کاراکترهایی که کلاً حذف می‌شوند: نیم‌فاصله و هم‌خانواده‌هایش، علامت‌های
 * جهت‌نما که از کپی‌پیست می‌آیند، کشیدهٔ تزئینی، و اعراب.
 */
const REMOVED =
  "​‌‍‎‏﻿" + // ZWSP ZWNJ ZWJ LRM RLM BOM
  "ـ" + // ـ کشیده
  "ًٌٍَُِّْٰ"; // اعراب

/**
 * دو رشته‌ای که به translate پستگرس داده می‌شوند. قرارداد translate: هر
 * کاراکترِ from که در to متناظری نداشته باشد حذف می‌شود — پس REMOVED عمداً
 * در انتهای from می‌آید و to کوتاه‌تر می‌ماند.
 */
export const FOLD_FROM = FOLD_PAIRS.map(([from]) => from).join("") + REMOVED;
export const FOLD_TO = FOLD_PAIRS.map(([, to]) => to).join("");

const FOLD_MAP = new Map(FOLD_PAIRS);

/** همان تبدیلِ بالا، روی ورودی کاربر */
export function normalizeSearchText(value: string): string {
  let out = "";
  for (const char of value) {
    const folded = FOLD_MAP.get(char);
    if (folded !== undefined) out += folded;
    else if (!REMOVED.includes(char)) out += char;
  }
  return out;
}

/** %  _  \ در ILIKE معنی دارند؛ ورودی کاربر باید متن ساده بماند نه الگو */
export function escapeLikePattern(value: string): string {
  return value.replace(/[\\%_]/g, (char) => `\\${char}`);
}

/**
 * شکستن عبارت به واژه‌ها. حذف نیم‌فاصله باعث می‌شود «آتش‌نشانی» در پایگاه داده
 * یک واژهٔ چسبیده شود، در حالی که کاربر «آتش نشانی» را با فاصله می‌نویسد؛
 * تطبیقِ واژه‌به‌واژه همین شکاف را پر می‌کند.
 */
export function searchTokens(value: string, max = 6): string[] {
  return normalizeSearchText(value).split(/\s+/).filter(Boolean).slice(0, max);
}

/** ستون، پس از همان یکسان‌سازی */
export function normalizedColumn(column: AnyColumn): SQL {
  return sql`translate(coalesce(${column}, ''), ${FOLD_FROM}, ${FOLD_TO})`;
}

/** ستونِ یکسان‌شده در برابر الگوی از پیش escape‌شده */
export function matchesPattern(column: AnyColumn, pattern: string): SQL {
  return sql`${normalizedColumn(column)} ilike ${pattern}`;
}
